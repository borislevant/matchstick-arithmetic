import {grantTestAccess} from './access-fixture.mjs';
import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {mkdir} from 'node:fs/promises';
const url=process.env.TEST_URL||'http://127.0.0.1:4173';
const browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{})});
await mkdir('artifacts',{recursive:true});
let checks=0;
const ok=(value,label)=>{assert.ok(value,label);checks++;};
try{
 for(const width of [320,390]){
  const page=await browser.newPage({viewport:{width,height:844},isMobile:true,hasTouch:true});
  await grantTestAccess(page);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const route=async id=>{await page.goto(`${url}/#/puzzle/${id}`);await page.waitForSelector('.puzzle-board');};
  const button=name=>page.getByRole('button',{name,exact:true});
  const moves=()=>page.locator('.move-counter b').innerText();
  const equation=()=>page.locator('.play-main > .sr-only[aria-live]').innerText();
  const board=()=>page.locator('.match').evaluateAll(els=>els.map(el=>[el.dataset.match,el.style.transform]).sort());
  const progress=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('matchstick-arithmetic-v1')));
  const place=async(from,to)=>{await page.locator(`[data-slot="${from}"]`).focus();await page.keyboard.press('Enter');await page.locator(`[data-slot="${to}"]`).focus();await page.keyboard.press('Enter');};
  await route('spark-01');
  ok(await page.locator('html').getAttribute('lang')==='ru','Fresh visit defaults to Russian');
  ok(await page.locator('.puzzle-title').innerText()==='1+1=3','Starting title appears at top');
  const labels=await page.locator('.play-actions button').allTextContents();
  assert.deepEqual(labels,['Отменить ход','Заново','Подсказка','Проверить','Решение']);checks++;
  const boxes=await page.locator('.play-actions button, .play-breadcrumb button, .puzzle-stepper button, .header-tools button, select').evaluateAll(els=>els.map(el=>{const r=el.getBoundingClientRect();return {w:r.width,h:r.height};}));
  ok(boxes.every(r=>r.w>=44&&r.h>=44),'Play controls have 44px targets');
  const bounds=await page.evaluate(()=>({top:document.querySelector('.play-summary').getBoundingClientRect().bottom,board:document.querySelector('.play-table').getBoundingClientRect(),actions:document.querySelector('.play-actions').getBoundingClientRect(),overflow:document.documentElement.scrollWidth>innerWidth}));
  ok(bounds.top<bounds.board.top&&bounds.board.bottom<bounds.actions.top,'Top, board, bottom order');
  ok(!bounds.overflow&&bounds.actions.bottom<=844,'All five controls fit the mobile viewport');
  const start=await board();
  await button('Проверить').tap();
  ok((await page.locator('.board-message').innerText()).trim()==='Ещё не сходится','Check toast matches requested Russian text');
  ok(await moves()==='0 / 1'&&await button('Отменить ход').isDisabled(),'Check does not spend a move or create undo history');
  await button('Подсказка').tap();
  ok(await page.locator('.hint-match').count()===1&&await page.locator('.target-slot').count()===0,'Hint 1 highlights only source');
  await page.getByRole('button',{name:/Подсказка/}).tap();
  ok(await page.locator('.target-slot').getAttribute('data-slot')==='4:4','Hint 2 highlights destination');
  ok(await moves()==='0 / 1','Hints do not consume moves');
  await page.screenshot({path:`artifacts/session4-hints-${width}.png`});
  await place('4:2','4:4');
  ok((await page.locator('.board-message').innerText()).trim()==='Верно!','Victory toast');
  await button('Отменить ход').tap();
  assert.deepEqual(await board(),start);checks++;
  ok(await moves()==='0 / 1'&&await page.locator('.target-slot,.hint-match').count()===0,'Undo restores budget and clears stale hints');
  await place('4:1','4:5');
  ok((await page.locator('.board-message').innerText()).trim()==='Ходы закончились','Exhaustion toast');
  await button('Заново').tap();assert.deepEqual(await board(),start);checks++;
  ok(await button('Отменить ход').isDisabled(),'Reset empties undo history');
  // Replay and undo two completed moves independently.
  await route('flame-01-v2');const hardStart=await board();
  await place('2:1','2:4');const middle=await board();
  await place('5:1','5:4');ok(await moves()==='2 / 2','Two moves recorded');
  await button('Отменить ход').tap();assert.deepEqual(await board(),middle);checks++;
  await button('Отменить ход').tap();assert.deepEqual(await board(),hardStart);checks++;
  ok(await moves()==='0 / 2'&&await button('Отменить ход').isDisabled(),'Undo stack ends at initial board');
  // Cancelling the solution must not mark the puzzle hinted.
  await route('spark-03');
  await button('Решение').tap();await button('Ещё подумаю').tap();
  ok(!(await progress()).hintedIds.includes('spark-03'),'Cancelled solution does not mark hinted');
  const demoStart=await board();
  await button('Решение').tap();await button('Показать').tap();
  ok((await progress()).hintedIds.includes('spark-03'),'Solution marks hinted immediately');
  ok(await page.locator('.puzzle-board.demonstrating').count()===1,'Solution enters animation');
  ok(await button('Проверить').isDisabled()&&await button('Отменить ход').isDisabled(),'Controls cannot interfere with animation');
  await page.waitForFunction(()=>document.querySelector('.move-counter b').textContent==='1 / 1');
  ok(await page.locator('.puzzle-board.demonstrating').count()===1,'Completed relocation is shown during animation');
  assert.notDeepEqual(await board(),demoStart);checks++;
  await page.getByRole('heading',{name:'Решение, шаг за шагом.',exact:true}).waitFor();
  ok((await equation()).includes('4+5=9'),'Animation ends at an accepted equation');
  ok(!(await progress()).solvedIds.includes('spark-03')&&await button('Проверить').isDisabled(),'Revealed solution cannot award solved progress via Check');
  await button('Заново').tap();assert.deepEqual(await board(),demoStart);checks++;
  await button('Решение').tap();await button('Показать').tap();await button('Заново').tap();
  await page.waitForTimeout(1500);
  assert.deepEqual(await board(),demoStart);checks++;
  ok(await moves()==='0 / 1','Reset cancels pending demonstration timers');
  await button('Решение').tap();await button('Показать').tap();await button('Все задачи').tap();
  await page.waitForTimeout(1500);await route('spark-03');
  assert.deepEqual(await board(),demoStart);checks++;
  ok(errors.length===0,errors.join(', '));
  await page.screenshot({path:`artifacts/session4-controls-${width}.png`});
  await page.close();
 }
 const blocked=await browser.newPage();
 await blocked.addInitScript(()=>{Storage.prototype.getItem=()=>{throw new Error('Blocked');};});
 await blocked.goto(url);await blocked.waitForSelector('.puzzle-card');
 ok(await blocked.locator('html').getAttribute('lang')==='ru','Blocked storage still defaults to Russian');
 console.log(`PASS: ${checks} controls checks at 320px and 390px.`);
}finally{await browser.close();}
